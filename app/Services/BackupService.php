<?php

namespace App\Services;

use App\Models\Backup;
use App\Contracts\StrategicLogWriter;
use App\Models\User;
use Illuminate\Contracts\Pagination\LengthAwarePaginator;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log as SystemLog;
use Illuminate\Support\Facades\Process;
use Illuminate\Support\Str;
use RuntimeException;

/**
 * Creates and serves manual database backups.
 *
 * Dumps are written to storage/app/backups, which sits outside the document
 * root — a backup contains every user record, password hash and plan in the
 * system, so it must never be reachable by URL. The only way to obtain one is
 * the download endpoint, which is permission-checked and audited.
 */
class BackupService
{
    public function __construct(private readonly StrategicLogWriter $logWriter) {}

    /** Seconds before a dump is abandoned. */
    private const TIMEOUT = 600;

    /** Longest failure reason kept in the database. */
    private const ERROR_LIMIT = 500;

    public function paginate(int $perPage = 15): LengthAwarePaginator
    {
        return Backup::query()
            ->with('creator')
            ->orderByDesc('created_at')
            ->orderByDesc('backup_id')
            ->paginate($perPage);
    }

    /**
     * Run a backup and record the outcome.
     *
     * Failures are recorded as a `failed` row and audited before being
     * rethrown, so an administrator can see that an attempt was made rather
     * than being left wondering whether the click registered.
     */
    public function create(User $actor): Backup
    {
        $connection = config('database.default');
        $driver = config("database.connections.{$connection}.driver");

        $filename = $this->generateFilename($driver);
        $path = null;

        try {
            $directory = $this->backupDirectory();
            $path = $directory . DIRECTORY_SEPARATOR . $filename;
            match ($driver) {
                'mysql', 'mariadb' => $this->dumpMysql($connection, $path),
                'sqlite' => $this->dumpSqlite($connection, $path),
                default => throw new RuntimeException(
                    "Backups are not supported for the {$driver} database driver."
                ),
            };
        } catch (\Throwable $exception) {
            // A partial file is worse than none: it looks restorable.
            if ($path !== null && is_file($path)) {
                @unlink($path);
            }

            $backup = Backup::create([
                'filename' => $filename,
                'size_bytes' => null,
                'driver' => (string) $driver,
                'status' => 'failed',
                'error_message' => $this->sanitize($exception->getMessage(), $connection),
                'created_by' => $actor->user_id,
            ]);

            $this->audit($actor, 'backup.failed', $backup, 'failed');

            throw $exception;
        }

        $backup = Backup::create([
            'filename' => $filename,
            'size_bytes' => is_file($path) ? filesize($path) : null,
            'driver' => (string) $driver,
            'status' => 'completed',
            'error_message' => null,
            'created_by' => $actor->user_id,
        ]);

        $this->audit($actor, 'backup.created', $backup, 'success');

        return $backup->load('creator');
    }

    /**
     * Absolute path of a completed backup, or null if the row or the file on
     * disk is gone.
     */
    public function pathFor(Backup $backup): ?string
    {
        if (! $backup->isDownloadable()) {
            return null;
        }

        // The filename is generated by this service and never supplied by a
        // caller, but it is still reduced to its basename and checked against
        // the backup directory so a tampered row cannot escape it.
        $directory = realpath($this->backupDirectory());
        if ($directory === false) {
            return null;
        }

        $path = realpath($directory . DIRECTORY_SEPARATOR . basename($backup->filename));

        if ($path === false || ! is_file($path)) {
            return null;
        }

        return str_starts_with($path, $directory . DIRECTORY_SEPARATOR) ? $path : null;
    }

    public function recordDownload(User $actor, Backup $backup): void
    {
        $this->audit($actor, 'backup.downloaded', $backup, 'success');
    }

    /**
     * Restore the database from a completed backup file.
     *
     * This is intentionally restricted to a deliberate manual action: it
     * replaces the current database contents with the selected backup and then
     * invalidates every active JWT session, because any token issued before
     * the restore was based on a different database state.
     */
    public function restore(User $actor, Backup $backup): void
    {
        if (! $backup->isRestorable()) {
            throw new RuntimeException('Only completed backups can be restored.');
        }

        $path = $this->pathFor($backup);
        if ($path === null) {
            throw new RuntimeException('This backup file is no longer available.');
        }

        $connection = config('database.default');
        $driver = config("database.connections.{$connection}.driver");

        if ($backup->driver !== (string) $driver) {
            throw new RuntimeException('This backup was created for a different database driver and cannot be restored here.');
        }

        match ($driver) {
            'mysql', 'mariadb' => $this->restoreMysql($connection, $path),
            'sqlite' => $this->restoreSqlite($connection, $path),
            default => throw new RuntimeException(
                "Restore is not supported for the {$driver} database driver."
            ),
        };

        $this->reconnectDefaultConnection($connection);

        User::query()->increment('auth_version');

        $restoredActor = User::query()->find($actor->user_id);

        if ($restoredActor) {
            $this->audit($restoredActor, 'backup.restored', $backup, 'success');
            return;
        }

        SystemLog::warning('Backup restored but the acting user does not exist in the restored database.', [
            'restored_backup_id' => $backup->backup_id,
            'restored_filename' => $backup->filename,
            'actor_user_id' => $actor->user_id,
        ]);
    }

    private function dumpMysql(string $connection, string $path): void
    {
        $config = config("database.connections.{$connection}");

        // Credentials go in a 0600 defaults file rather than on the command
        // line, where any local user could read them out of the process list.
        $defaultsFile = tempnam(sys_get_temp_dir(), 'spdms-dump-');

        if ($defaultsFile === false) {
            throw new RuntimeException('A temporary file for the backup could not be created.');
        }

        try {
            chmod($defaultsFile, 0600);
            file_put_contents($defaultsFile, $this->mysqlDefaults($config));


            $processEnvironment = [];

            if (PHP_OS_FAMILY === 'Windows') {
                $systemRoot = getenv('SystemRoot')
                    ?: getenv('WINDIR')
                    ?: ($_SERVER['SystemRoot'] ?? null)
                    ?: ($_SERVER['WINDIR'] ?? null);

                if (! is_string($systemRoot) || $systemRoot === '') {
                    throw new RuntimeException(
                        'The Windows SystemRoot environment variable is unavailable to PHP.'
                    );
                }

                $processEnvironment = [
                    'SystemRoot' => $systemRoot,
                    'WINDIR' => $systemRoot,
                ];
            }

            // Array form, so no argument is ever parsed by a shell.
            $result = Process::env($processEnvironment)
                ->timeout(self::TIMEOUT)
                ->run([
                    (string) config('backup.mysqldump_path', 'mysqldump'),
                    '--defaults-extra-file=' . $defaultsFile,
                    '--single-transaction',
                    '--skip-lock-tables',
                    '--routines',
                    '--triggers',
                    '--events',
                    '--no-tablespaces',
                    '--result-file=' . $path,
                    $config['database'],
                ]);

            if (! $result->successful()) {
                throw new RuntimeException(
                    'mysqldump failed: ' . trim($result->errorOutput() ?: $result->output())
                );
            }
        } finally {
            @unlink($defaultsFile);
        }
    }

    private function mysqlDefaults(array $config): string
    {
        $lines = [
            '[client]',
            'user=' . ($config['username'] ?? ''),
            'password=' . ($config['password'] ?? ''),
        ];

        // A unix socket takes precedence over host/port when configured.
        if (! empty($config['unix_socket'])) {
            $lines[] = 'socket=' . $config['unix_socket'];
        } else {
            $lines[] = 'host=' . ($config['host'] ?? '127.0.0.1');
            $lines[] = 'port=' . ($config['port'] ?? 3306);
        }

        return implode(PHP_EOL, $lines) . PHP_EOL;
    }

    /**
     * SQLite has no dump binary in play — the database is a single file, so a
     * copy is the backup. Used by the test suite and local installs.
     */
    private function dumpSqlite(string $connection, string $path): void
    {
        $database = config("database.connections.{$connection}.database");

        if (! is_string($database) || $database === '' || ! is_file($database)) {
            throw new RuntimeException('The SQLite database file could not be found.');
        }

        if (! copy($database, $path)) {
            throw new RuntimeException('The SQLite database file could not be copied.');
        }
    }

    private function restoreMysql(string $connection, string $path): void
    {
        $config = config("database.connections.{$connection}");
        $defaultsFile = tempnam(sys_get_temp_dir(), 'spdms-restore-');

        if ($defaultsFile === false) {
            throw new RuntimeException('A temporary file for the restore could not be created.');
        }

        try {
            chmod($defaultsFile, 0600);
            file_put_contents($defaultsFile, $this->mysqlDefaults($config));

            $result = Process::path(dirname($path))
                ->timeout(self::TIMEOUT)
                ->run([
                    'mysql',
                    '--defaults-extra-file=' . $defaultsFile,
                    '--database=' . $config['database'],
                    '--execute=source ' . basename($path),
                ]);

            if (! $result->successful()) {
                throw new RuntimeException(
                    'mysql restore failed: ' . trim($result->errorOutput() ?: $result->output())
                );
            }
        } finally {
            @unlink($defaultsFile);
        }
    }

    private function restoreSqlite(string $connection, string $path): void
    {
        $database = config("database.connections.{$connection}.database");

        if (! is_string($database) || $database === '' || $database === ':memory:') {
            throw new RuntimeException('The SQLite database file could not be found.');
        }

        $directory = dirname($database);

        if (! is_dir($directory)) {
            throw new RuntimeException('The SQLite database directory could not be found.');
        }

        $staged = $database . '.restore-' . Str::lower(Str::random(8));
        $original = $database . '.pre-restore-' . Str::lower(Str::random(8));

        if (! copy($path, $staged)) {
            throw new RuntimeException('The selected backup file could not be staged for restore.');
        }

        $this->disconnectDefaultConnection($connection);

        try {
            if (is_file($database) && ! @rename($database, $original)) {
                throw new RuntimeException('The current SQLite database file could not be prepared for restore.');
            }

            if (! @rename($staged, $database)) {
                if (is_file($original)) {
                    @rename($original, $database);
                }

                throw new RuntimeException('The SQLite backup file could not be restored.');
            }

            if (is_file($original)) {
                @unlink($original);
            }
        } finally {
            if (is_file($staged)) {
                @unlink($staged);
            }
        }
    }

    private function generateFilename(?string $driver): string
    {
        $extension = in_array($driver, ['sqlite'], true) ? 'sqlite' : 'sql';

        // The random suffix keeps filenames unguessable and avoids a collision
        // when two backups are started in the same second.
        return sprintf(
            'spdms-backup-%s-%s.%s',
            now()->format('Ymd-His'),
            Str::lower(Str::random(8)),
            $extension
        );
    }

    private function backupDirectory(): string
    {
        $directory = storage_path('app/backups');

        if (! is_dir($directory) && ! @mkdir($directory, 0750, true) && ! is_dir($directory)) {
            throw new RuntimeException('The backup directory could not be created.');
        }

        return $directory;
    }

    /**
     * Strip the database password out of a failure message before it is
     * stored, in case a tool echoes it back, and cap the length.
     */
    private function sanitize(string $message, string $connection): string
    {
        $password = (string) config("database.connections.{$connection}.password");

        if ($password !== '') {
            $message = str_replace($password, '[redacted]', $message);
        }

        return Str::limit($message, self::ERROR_LIMIT);
    }

    private function audit(User $actor, string $event, Backup $backup, string $state): void
    {
        $this->logWriter->write($event, [
            'actor_user_id' => $actor->user_id,
            'resource_type' => 'backup',
            'resource_id' => $backup->backup_id,
            'outcome' => $state === 'failed' ? 'failure' : 'success',
            'backup_id' => $backup->backup_id,
            'filename' => $backup->filename,
            'states' => $state,
        ]);
    }

    private function disconnectDefaultConnection(string $connection): void
    {
        DB::disconnect($connection);
        DB::purge($connection);
    }

    private function reconnectDefaultConnection(string $connection): void
    {
        DB::purge($connection);
        DB::reconnect($connection);
    }
}
