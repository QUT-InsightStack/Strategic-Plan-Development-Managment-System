/**
 * Builds the Technical Administration activity report, using the same section/table contract as the
 * Management report master so the frontend renders both with one component. Sections the user has
 * no permission for are omitted and listed on the cover; the Technical Admin dashboard reads the same data.
 */
class TechnicalActivityReportService
{
    public const PERIODS = [7, 30, 90];

    public const SECTIONS = [
        'cover' => ['number' => 0, 'title' => 'Report Information', 'permissions' => []],
        'summary' => ['number' => 1, 'title' => 'Technical Summary', 'permissions' => []],
        'accounts' => ['number' => 2, 'title' => 'User Accounts', 'permissions' => ['users.view']],
        'signins' => ['number' => 3, 'title' => 'Sign-in Activity', 'permissions' => ['login_history.view']],
        'audit' => ['number' => 4, 'title' => 'Audit Activity', 'permissions' => ['logs.view']],
        'assistance' => ['number' => 5, 'title' => 'Password Assistance', 'permissions' => ['users.update']],
        'health' => ['number' => 6, 'title' => 'System Health', 'permissions' => ['system_monitoring.view']],
        'backups' => ['number' => 7, 'title' => 'Backups', 'permissions' => ['backups.view']],
        'workflow' => ['number' => 8, 'title' => 'Approval Workflow', 'permissions' => ['@workflow']],
        'annex' => ['number' => 9, 'title' => 'Annex: Definitions', 'permissions' => []],
    ];

    /** Sections that hold technical data; a user needs at least one of them to open the report. */
    private const DATA_SECTIONS = ['accounts', 'signins', 'audit', 'assistance', 'health', 'backups', 'workflow'];

    private const ASSISTANCE_LABELS = [
        PasswordAssistanceRequest::PENDING => 'Pending', PasswordAssistanceRequest::ACCEPTED => 'Accepted',
        PasswordAssistanceRequest::ACTED_ON => 'Password reset', PasswordAssistanceRequest::IGNORED => 'Ignored',
    ];

    public function __construct(
        private readonly PermissionAuthorizationService $permissions,
        private readonly SystemMonitoringService $monitoring,
    ) {}

    public function canView(User $user): bool
    {
        return collect(self::DATA_SECTIONS)->contains(fn (string $id) => $this->allowed($user, $id));
    }

    public function build(User $user, array $filters, ?CarbonImmutable $now = null): array
    {
        $now ??= CarbonImmutable::now();
        $days = in_array((int) ($filters['days'] ?? 0), self::PERIODS, true) ? (int) $filters['days'] : 30;
        $from = $now->subDays($days)->startOfDay();
        $allowed = collect(array_keys(self::SECTIONS))->mapWithKeys(fn (string $id) => [$id => $this->allowed($user, $id)]);
        $context = compact('user', 'now', 'days', 'from', 'allowed');

        $sections = [];
        $omitted = [];
        foreach (array_keys(self::SECTIONS) as $id) {
            if ($id === 'cover') {
                continue;
            }
            if (! $allowed[$id]) {
                $omitted[] = ['id' => $id, 'number' => self::SECTIONS[$id]['number'], 'title' => self::SECTIONS[$id]['title'],
                    'reason' => $id === 'workflow' ? 'Requires an administrator role that configures approval workflows.'
                        : 'Requires '.implode(' or ', self::SECTIONS[$id]['permissions']).'.'];

                continue;
            }
            $sections[] = ['id' => $id, 'number' => self::SECTIONS[$id]['number'], 'title' => self::SECTIONS[$id]['title'], ...$this->{'section'.ucfirst($id)}($context)];
        }

        $period = "Last {$days} days (".$from->format('j M Y').' – '.$now->format('j M Y').')';
        $meta = [
            'title' => 'Technical Administration Activity Report',
            'generated_at' => $now->toIso8601String(),
            'generated_by' => trim(($user->first_name ?? '').' '.($user->last_name ?? '')) ?: $user->email,
            'role' => $user->role?->role_name,
            'planning_period' => $period,
            'days' => $days,
            'filters' => [['label' => 'Activity period', 'value' => "Last {$days} days"]],
            'scope' => 'System-wide technical activity. Planning content is not included.',
        ];
        $cover = ['id' => 'cover', 'number' => 0, 'title' => self::SECTIONS['cover']['title'], 'fields' => [
            ['label' => 'Report', 'value' => $meta['title']],
            ['label' => 'Activity period', 'value' => $period],
            ['label' => 'Generated by', 'value' => $meta['generated_by'].($meta['role'] ? " ({$meta['role']})" : '')],
            ['label' => 'Generated at', 'value' => $now->format('j M Y, H:i T')],
            ['label' => 'Data scope', 'value' => $meta['scope']],
            ['label' => 'Sections omitted', 'value' => $omitted ? collect($omitted)->map(fn ($s) => "{$s['number']}. {$s['title']}")->implode('; ').' — omitted because of access permissions, not because they are empty.' : 'None'],
        ]];

        return ['meta' => $meta, 'sections' => [$cover, ...$sections], 'omitted_sections' => $omitted];
    }

    /** @return array{0: string, 1: array, 2: array} [title, columns, rows] */
    public function table(array $report, string $sectionId, ?string $tableId = null): ?array
    {
        $section = collect($report['sections'])->firstWhere('id', $sectionId);
        $tables = collect($section['tables'] ?? []);
        $table = $tableId ? $tables->firstWhere('id', $tableId) : $tables->first();

        return $table ? [$table['title'], $table['columns'], $table['rows']] : null;
    }

    public function isOmitted(array $report, string $sectionId): bool
    {
        return collect($report['omitted_sections'])->contains('id', $sectionId);
    }

    private function sectionSummary(array $c): array
    {
        $a = $c['allowed'];
        $kpis = [];
        // Follow-up items for the dashboard's Attention Required card; each links to the page that resolves it.
        $attention = [];
        if ($a['accounts']) {
            $active = User::where('status', 'active')->count();
            $locked = User::where('locked_until', '>', $c['now'])->count();
            $kpis[] = $this->kpi('accounts', 'Active Accounts', $active, User::count()." accounts in total · {$locked} locked", 'bi-people-fill', 'blue');
            $attention[] = $this->attention('locked', 'Locked accounts', $locked, 'Temporarily locked after failed sign-ins', '/user-management');
        } else {
            $kpis[] = $this->unavailable('accounts', 'Active Accounts', 'bi-people-fill', 'blue');
        }
        if ($a['signins']) {
            $signins = LoginHistory::where('attempted_at', '>=', $c['from'])->selectRaw("SUM(CASE WHEN status = 'success' THEN 1 ELSE 0 END) AS ok, SUM(CASE WHEN status = 'failed' THEN 1 ELSE 0 END) AS failed")->first();
            $kpis[] = $this->kpi('signins', 'Successful Sign-ins', (int) $signins->ok, ((int) $signins->failed)." failed sign-ins · last {$c['days']} days", 'bi-box-arrow-in-right', 'green');
            $attention[] = $this->attention('failed_signins', 'Failed sign-ins', (int) $signins->failed, "Last {$c['days']} days", '/login-history');
        } else {
            $kpis[] = $this->unavailable('signins', 'Successful Sign-ins', 'bi-box-arrow-in-right', 'green');
        }
        if ($a['audit']) {
            $events = Log::where('created_at', '>=', $c['from'])->count();
            $failures = Log::where('created_at', '>=', $c['from'])->whereIn('outcome', ['failure', 'denied'])->count();
            $kpis[] = $this->kpi('audit', 'Audit Events', $events, "{$failures} failed or denied · last {$c['days']} days", 'bi-journal-text', 'purple');
            $attention[] = $this->attention('audit_failures', 'Failed or denied actions', $failures, "Audit events, last {$c['days']} days", '/audit-logs');
        } else {
            $kpis[] = $this->unavailable('audit', 'Audit Events', 'bi-journal-text', 'purple');
        }
        if ($a['assistance']) {
            $pending = PasswordAssistanceRequest::whereIn('status', [PasswordAssistanceRequest::PENDING, PasswordAssistanceRequest::ACCEPTED])->count();
            $kpis[] = $this->kpi('assistance', 'Password Assistance', $pending, 'Open requests awaiting action', 'bi-key-fill', 'cyan');
            $attention[] = $this->attention('assistance', 'Open password assistance requests', $pending, 'Pending or accepted, not yet resolved', '/user-management');
        } else {
            $kpis[] = $this->unavailable('assistance', 'Password Assistance', 'bi-key-fill', 'cyan');
        }
        if ($a['health']) {
            $open = SystemAlert::where('status', 'open')->count();
            $status = SystemCheck::orderByDesc('id')->value('status');
            $kpis[] = $this->kpi('alerts', 'Open System Alerts', $open, 'Latest health check: '.($status ? ucfirst($status) : 'not run yet'), 'bi-activity', 'amber');
            $attention[] = $this->attention('alerts', 'Open system alerts', $open, 'Conditions still present at the latest check', '/system-monitoring');
        } else {
            $kpis[] = $this->unavailable('alerts', 'Open System Alerts', 'bi-activity', 'amber');
        }
        if ($a['backups']) {
            $last = Backup::where('status', 'completed')->orderByDesc('created_at')->first();
            $failed = Backup::where('status', 'failed')->where('created_at', '>=', $c['from'])->count();
            $kpis[] = $this->kpi('backups', 'Last Successful Backup', $last ? CarbonImmutable::parse($last->created_at)->format('j M Y') : 'None',
                "{$failed} failed backups · last {$c['days']} days", 'bi-hdd-stack-fill', 'red');
            $attention[] = $this->attention('failed_backups', 'Failed backups', $failed, "Last {$c['days']} days", '/manual-backup');
        } else {
            $kpis[] = $this->unavailable('backups', 'Last Successful Backup', 'bi-hdd-stack-fill', 'red');
        }

        return ['description' => "Headline technical figures for the last {$c['days']} days; they match the Technical Administration Dashboard cards.", 'kpis' => $kpis, 'attention' => $attention, 'tables' => [[
            'id' => 'kpis', 'title' => 'Technical summary', 'columns' => $this->columns(['indicator' => 'Indicator', 'value' => 'Value', 'detail' => 'Detail']),
            'rows' => array_map(fn ($kpi) => ['indicator' => $kpi['label'], 'value' => $kpi['value'] ?? 'No access', 'detail' => $kpi['detail']], $kpis),
        ]]];
    }

    private function sectionAccounts(array $c): array
    {
        $users = User::with('role:role_id,role_name')->get(['user_id', 'role_id', 'status', 'locked_until', 'created_at', 'first_name', 'last_name', 'email']);
        $byRole = $users->groupBy(fn (User $user) => $user->role?->role_name ?? 'No role')
            ->map(fn (Collection $rows, string $role) => [
                'role' => $role, 'active' => $rows->where('status', 'active')->count(),
                'inactive' => $rows->where('status', 'inactive')->count(),
                'other' => $rows->whereNotIn('status', ['active', 'inactive'])->count(),
                'locked' => $rows->filter(fn (User $user) => $user->locked_until?->greaterThan($c['now']))->count(),
                'total' => $rows->count(),
            ])->sortKeys(SORT_NATURAL | SORT_FLAG_CASE)->values()->all();
        $recent = $users->filter(fn (User $user) => $user->created_at && CarbonImmutable::parse($user->created_at)->greaterThanOrEqualTo($c['from']))
            ->sortByDesc('created_at')->map(fn (User $user) => [
                'name' => trim("{$user->first_name} {$user->last_name}") ?: $user->email, 'email' => $user->email,
                'role' => $user->role?->role_name ?? 'No role', 'status' => ucfirst((string) $user->status),
                'created_at' => CarbonImmutable::parse($user->created_at)->toDateString(),
            ])->values()->all();

        return ['description' => "{$users->where('status', 'active')->count()} of {$users->count()} accounts are active.", 'tables' => [
            ['id' => 'roles', 'title' => 'Accounts by role', 'columns' => $this->columns(['role' => 'Role', 'active' => 'Active', 'inactive' => 'Inactive', 'other' => 'Other status', 'locked' => 'Locked now', 'total' => 'Total']), 'rows' => $byRole],
            ['id' => 'new_accounts', 'title' => "Accounts created in the last {$c['days']} days", 'columns' => $this->columns(['name' => 'Name', 'email' => 'Email', 'role' => 'Role', 'status' => 'Status', 'created_at' => 'Created']), 'rows' => $recent],
        ]];
    }

    private function sectionSignins(array $c): array
    {
        $attempts = LoginHistory::where('attempted_at', '>=', $c['from'])->orderBy('attempted_at')->get(['email', 'status', 'failure_reason', 'attempted_at']);
        $daily = $attempts->groupBy(fn ($row) => $row->attempted_at->toDateString())
            ->map(fn (Collection $rows, string $date) => ['date' => $date, 'successful' => $rows->where('status', 'success')->count(), 'failed' => $rows->where('status', 'failed')->count(), 'total' => $rows->count()])
            ->sortKeysDesc()->values()->all();
        $failing = $attempts->where('status', 'failed')->groupBy(fn ($row) => strtolower((string) $row->email))
            ->map(fn (Collection $rows, string $email) => ['email' => $email ?: '—', 'failed' => $rows->count(),
                'last_reason' => str_replace('_', ' ', (string) $rows->last()->failure_reason), 'last_attempt' => $rows->last()->attempted_at->format('Y-m-d H:i')])
            ->sortByDesc('failed')->take(10)->values()->all();
        $failed = $attempts->where('status', 'failed')->count();

        return ['description' => "{$attempts->count()} sign-in attempts in the last {$c['days']} days, {$failed} failed (".$this->percent($failed, $attempts->count()).'%).', 'tables' => [
            ['id' => 'daily', 'title' => 'Sign-ins per day', 'columns' => $this->columns(['date' => 'Date', 'successful' => 'Successful', 'failed' => 'Failed', 'total' => 'Total']), 'rows' => $daily],
            ['id' => 'failing_accounts', 'title' => 'Accounts with most failed sign-ins', 'columns' => $this->columns(['email' => 'Email', 'failed' => 'Failed attempts', 'last_reason' => 'Last reason', 'last_attempt' => 'Last attempt']), 'rows' => $failing],
        ]];
    }

    private function sectionAudit(array $c): array
    {
        $logs = Log::where('created_at', '>=', $c['from'])->orderByDesc('log_id')->get(['log_id', 'actor_name', 'operation', 'resource_type', 'outcome', 'created_at']);
        $byEvent = $logs->groupBy(fn (Log $log) => $log->eventName())
            ->map(fn (Collection $rows, string $event) => ['event' => $event, 'total' => $rows->count(),
                'successful' => $rows->whereNotIn('outcome', ['failure', 'denied'])->count(),
                'failed' => $rows->where('outcome', 'failure')->count(), 'denied' => $rows->where('outcome', 'denied')->count()])
            ->sortByDesc('total')->take(15)->values()->all();
        $problems = $logs->whereIn('outcome', ['failure', 'denied'])->take(20)->map(fn (Log $log) => [
            'occurred_at' => $log->created_at?->format('Y-m-d H:i') ?? '', 'actor' => $log->actor_name ?: 'System',
            'event' => $log->eventName(), 'resource' => str_replace('_', ' ', (string) $log->resource_type), 'outcome' => ucfirst((string) $log->outcome),
        ])->values()->all();

        return ['description' => "{$logs->count()} audit events recorded in the last {$c['days']} days.", 'tables' => [
            ['id' => 'events', 'title' => 'Most frequent audit events', 'columns' => $this->columns(['event' => 'Event', 'total' => 'Total', 'successful' => 'Successful', 'failed' => 'Failed', 'denied' => 'Denied']), 'rows' => $byEvent],
            ['id' => 'failures', 'title' => 'Latest failed or denied events', 'columns' => $this->columns(['occurred_at' => 'Time', 'actor' => 'Actor', 'event' => 'Event', 'resource' => 'Resource', 'outcome' => 'Outcome']), 'rows' => $problems],
        ]];
    }

    private function sectionAssistance(array $c): array
    {
        $requests = PasswordAssistanceRequest::with('user:user_id,first_name,last_name,email', 'handledBy:user_id,first_name,last_name')
            ->where('created_at', '>=', $c['from'])->orderByDesc('created_at')->get();
        $open = PasswordAssistanceRequest::whereIn('status', [PasswordAssistanceRequest::PENDING, PasswordAssistanceRequest::ACCEPTED])->count();
        $byStatus = collect(self::ASSISTANCE_LABELS)->map(fn ($label, $status) => ['status' => $label, 'requests' => $requests->where('status', $status)->count()])->values()->all();

        return ['description' => "{$open} requests are open. Figures below cover requests made in the last {$c['days']} days.", 'tables' => [
            ['id' => 'assistance_status', 'title' => 'Requests by status', 'columns' => $this->columns(['status' => 'Status', 'requests' => 'Requests']), 'rows' => $byStatus],
            ['id' => 'assistance_requests', 'title' => 'Requests', 'columns' => $this->columns(['requested_at' => 'Requested', 'user' => 'User', 'status' => 'Status', 'handled_by' => 'Handled by', 'handled_at' => 'Handled']),
                'rows' => $requests->take(25)->map(fn (PasswordAssistanceRequest $request) => [
                    'requested_at' => $request->created_at?->format('Y-m-d H:i') ?? '',
                    'user' => $request->user ? (trim("{$request->user->first_name} {$request->user->last_name}") ?: $request->user->email) : 'Deleted user',
                    'status' => self::ASSISTANCE_LABELS[$request->status] ?? ucfirst((string) $request->status),
                    'handled_by' => $request->handledBy ? trim("{$request->handledBy->first_name} {$request->handledBy->last_name}") : '',
                    'handled_at' => $request->handled_at?->format('Y-m-d H:i') ?? '',
                ])->values()->all()],
        ]];
    }

    private function sectionHealth(array $c): array
    {
        $metrics = [];
        try {
            $summary = $this->monitoring->summary($c['days'] * 1440, $c['from'], $c['now']);
            $metrics = [
                ['indicator' => 'Requests', 'value' => $summary['requests'], 'detail' => "Last {$c['days']} days"],
                ['indicator' => 'Server error rate', 'value' => $summary['error_rate_percent'].'%', 'detail' => "{$summary['server_errors']} server errors · {$summary['client_errors']} client errors"],
                ['indicator' => 'Slow requests', 'value' => $summary['slow_requests'], 'detail' => "At least {$summary['thresholds']['slow_request_ms']} ms"],
                ['indicator' => 'Average response time', 'value' => $summary['average_duration_ms'].' ms', 'detail' => "Slowest {$summary['max_duration_ms']} ms"],
                ['indicator' => 'Slow database requests', 'value' => $summary['slow_database_requests'], 'detail' => "At least {$summary['thresholds']['slow_database_ms']} ms in the database"],
            ];
        } catch (Throwable) {
            $metrics = [['indicator' => 'Request metrics', 'value' => 'Unavailable', 'detail' => 'Monitoring tables could not be read.']];
        }
        $latest = SystemCheck::orderByDesc('id')->first();
        $alerts = SystemAlert::where('status', 'open')->orWhere('opened_at', '>=', $c['from'])->orderByDesc('opened_at')->take(25)->get()
            ->map(fn (SystemAlert $alert) => [
                'condition' => str_replace(['.', '_'], [' · ', ' '], (string) $alert->condition), 'severity' => ucfirst((string) $alert->severity),
                'status' => ucfirst((string) $alert->status), 'occurrences' => $alert->occurrences,
                'opened_at' => $alert->opened_at?->format('Y-m-d H:i') ?? '', 'resolved_at' => $alert->resolved_at?->format('Y-m-d H:i') ?? '',
            ])->values()->all();

        return ['description' => 'Latest health check: '.($latest ? ucfirst((string) $latest->status).' at '.CarbonImmutable::parse($latest->checked_at ?? $latest->created_at)->format('j M Y, H:i') : 'not run yet').'.', 'tables' => [
            ['id' => 'metrics', 'title' => 'Request metrics', 'columns' => $this->columns(['indicator' => 'Indicator', 'value' => 'Value', 'detail' => 'Detail']), 'rows' => $metrics],
            ['id' => 'alerts', 'title' => 'Open and recent alerts', 'columns' => $this->columns(['condition' => 'Condition', 'severity' => 'Severity', 'status' => 'Status', 'occurrences' => 'Occurrences', 'opened_at' => 'Opened', 'resolved_at' => 'Resolved']), 'rows' => $alerts],
        ]];
    }

    private function sectionBackups(array $c): array
    {
        $backups = Backup::with('creator:user_id,first_name,last_name')->where('created_at', '>=', $c['from'])->orderByDesc('created_at')->take(25)->get();
        $completed = $backups->where('status', 'completed')->count();

        return ['description' => "{$backups->count()} backups in the last {$c['days']} days, {$completed} completed.", 'tables' => [[
            'id' => 'backups', 'title' => 'Backup history',
            'columns' => $this->columns(['created_at' => 'Created', 'filename' => 'File', 'status' => 'Status', 'size' => 'Size', 'created_by' => 'Created by']),
            'rows' => $backups->map(fn (Backup $backup) => [
                'created_at' => $backup->created_at?->format('Y-m-d H:i') ?? '', 'filename' => $backup->filename, 'status' => ucfirst((string) $backup->status),
                'size' => $backup->size_bytes ? round($backup->size_bytes / 1048576, 2).' MB' : '',
                'created_by' => $backup->creator ? trim("{$backup->creator->first_name} {$backup->creator->last_name}") : 'System',
            ])->values()->all(),
        ]]];
    }

    private function sectionWorkflow(array $c): array
    {
        $workflow = ApprovalWorkflow::with('stages')->find(1);
        $users = User::whereIn('user_id', $workflow?->stages->pluck('user_id')->filter() ?? [])->get(['user_id', 'first_name', 'last_name'])->keyBy('user_id');
        $roles = Role::whereIn('role_id', $workflow?->stages->pluck('role_id')->filter() ?? [])->pluck('role_name', 'role_id');

        return ['description' => $workflow ? "{$workflow->name}: ".ucfirst((string) $workflow->status).", version {$workflow->version}, {$workflow->stages->count()} stages." : 'No approval workflow is configured.', 'tables' => [[
            'id' => 'stages', 'title' => 'Approval stages',
            'columns' => $this->columns(['sequence' => 'Order', 'stage' => 'Stage', 'approver' => 'Approver']),
            'rows' => ($workflow?->stages ?? collect())->map(fn ($stage) => [
                'sequence' => $stage->sequence, 'stage' => $stage->name,
                'approver' => $stage->user_id ? 'User: '.trim(($users[$stage->user_id]->first_name ?? '').' '.($users[$stage->user_id]->last_name ?? ''))
                    : ($stage->role_id ? 'Role: '.($roles[$stage->role_id] ?? "Role {$stage->role_id}") : 'Not assigned'),
            ])->values()->all(),
        ]]];
    }

    private function sectionAnnex(array $c): array
    {
        return ['description' => 'Definitions used throughout this report.', 'definitions' => [
            ['term' => 'Activity period', 'definition' => 'Counts cover the selected number of days up to the time the report was generated. Account and alert totals are current values.'],
            ['term' => 'Locked account', 'definition' => 'An account temporarily locked after repeated failed sign-ins; it unlocks automatically when the lock period ends.'],
            ['term' => 'Failed or denied event', 'definition' => 'An audit event whose outcome is failure (the action did not complete) or denied (the user lacked permission).'],
            ['term' => 'Open password assistance', 'definition' => 'Requests that are pending or accepted but not yet resolved by a password reset or ignore.'],
            ['term' => 'Open system alert', 'definition' => 'A monitoring condition that is still present at the latest health check. It resolves automatically when the condition clears.'],
            ['term' => 'Data scope', 'definition' => 'System-wide technical records only. Sections you cannot access are omitted and listed on the cover.'],
        ]];
    }

    private function allowed(User $user, string $id): bool
    {
        $codes = self::SECTIONS[$id]['permissions'];
        if ($codes === ['@workflow']) {
            return $user->status === 'active' && in_array($user->role?->role_name, Role::PRIVILEGED_ROLES, true);
        }
        if ($codes === []) {
            return $id === 'annex' || $id === 'summary' ? $this->canView($user) : true;
        }

        return (bool) $user->role?->hasFullAccess() || $this->permissions->userPermissionCodes($user)->intersect($codes)->isNotEmpty();
    }

    private function kpi(string $key, string $label, int|string $value, string $detail, string $icon, string $tone): array
    {
        return compact('key', 'label', 'value', 'detail', 'icon', 'tone') + ['available' => true];
    }

    private function attention(string $key, string $label, int $count, string $detail, string $href): array
    {
        return compact('key', 'label', 'count', 'detail', 'href');
    }

    private function unavailable(string $key, string $label, string $icon, string $tone): array
    {
        return ['key' => $key, 'label' => $label, 'value' => null, 'detail' => 'No access', 'icon' => $icon, 'tone' => $tone, 'available' => false];
    }

    private function columns(array $columns): array
    {
        return collect($columns)->map(fn ($label, $key) => ['key' => $key, 'label' => $label])->values()->all();
    }

    private function percent(int $part, int $total): int
    {
        return $total ? (int) round($part * 100 / $total) : 0;
    }
}
